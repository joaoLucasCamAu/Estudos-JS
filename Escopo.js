/* Aula 2: ESCOPO 

Esta aula visa ensinar ou elucidar o conceito de escopo em JS. Escopo é como um ambiente ou categoria em que as váriaveis
podem fazer parte. Existem três tipos: 
1. Escopo Global
2. Escopo Local
3. Escopo de Bloco

1 - ESCOPO GLOBAL: é o escopo que engloba todo o código, ou seja, as variáveis declaradas nesse escopo podem ser acessadas de 
qualquer lugar do código. Váriaveis delcaradas fora de qualquer funcção ou laço de repetição são consideradas globais.

2- ESCOPO LOCAL(Ou de Função): é o escopo que engloba apenas uma função, variavéis declaradas somente dentro de uma função
são consideradas locais e só podem ser acessadas dentro dessa função.

3- ESCOPO DE BLOCO: é o escopo que engloba apenas um bloco de código, variáveis declaradas dentro de um bloco de código
são consideradas de bloco e só podem ser acessadas dentro desse bloco. Blocos de código são delimitados por chaves {}.
Exemplo de escopo de bloco: if, for, while, switch, try/catch, etc.

*/